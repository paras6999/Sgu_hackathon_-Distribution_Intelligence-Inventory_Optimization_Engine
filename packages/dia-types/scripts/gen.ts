/**
 * Code generation for @dia/types (owner: M2).
 *
 *   schema/*.schema.json  (SOURCE OF TRUTH, edited by hand)
 *     -> dist/dia.schema.json        bundled schema (backend validation, Python codegen input)
 *     -> ts/generated.ts             TypeScript types (backend, web)
 *     -> py/dia_types/models.py      pydantic v2 models (engine)
 *
 * `bun scripts/gen.ts --check` regenerates into memory and fails if committed files differ (CI).
 */
import { readdirSync, readFileSync, writeFileSync, mkdtempSync } from "node:fs";
import { join, resolve } from "node:path";
import { tmpdir } from "node:os";
import { compile } from "json-schema-to-typescript";

const ROOT = resolve(import.meta.dir, "..");
const CHECK = process.argv.includes("--check");
const DATAMODEL_CODEGEN = "datamodel-code-generator==0.34.0";

function bundle(): Record<string, unknown> {
  const defs: Record<string, unknown> = {};
  const owner: Record<string, string> = {};
  for (const file of readdirSync(join(ROOT, "schema")).filter((f) => f.endsWith(".schema.json")).sort()) {
    const doc = JSON.parse(readFileSync(join(ROOT, "schema", file), "utf8"));
    for (const [name, def] of Object.entries(doc.$defs ?? {})) {
      if (owner[name]) throw new Error(`${name} defined in both ${owner[name]} and ${file}`);
      owner[name] = file;
      defs[name] = def;
    }
  }
  const text = JSON.stringify(defs);
  for (const m of text.matchAll(/"\$ref":"#\/\$defs\/([A-Za-z0-9_]+)"/g)) {
    if (!defs[m[1]!]) throw new Error(`unresolved $ref ${m[1]}`);
  }
  return { $schema: "https://json-schema.org/draft/2020-12/schema", $id: "dia", title: "Dia", $defs: defs };
}

/** json-schema-to-typescript turns {$ref, default} into a duplicate type (Foo1); defaults don't matter for TS types. */
function dropRefDefaults(node: unknown): unknown {
  if (Array.isArray(node)) return node.map(dropRefDefaults);
  if (node && typeof node === "object") {
    const obj = node as Record<string, unknown>;
    const out: Record<string, unknown> = {};
    for (const [k, v] of Object.entries(obj)) {
      if (k === "default" && "$ref" in obj) continue;
      out[k] = dropRefDefaults(v);
    }
    return out;
  }
  return node;
}

async function typescript(schema: Record<string, unknown>): Promise<string> {
  const input = dropRefDefaults({ ...schema, type: "object", additionalProperties: false });
  const ts = await compile(input as never, "Dia", {
    bannerComment: "/* GENERATED by packages/dia-types/scripts/gen.ts from schema/*.schema.json. DO NOT EDIT. */",
    unreachableDefinitions: true,
    additionalProperties: false,
    format: true,
    style: { singleQuote: false, printWidth: 120 },
  });
  return ts.replace(/export interface Dia \{\}\n?/, "");
}

function python(bundledPath: string): string {
  const outDir = mkdtempSync(join(tmpdir(), "dia-types-"));
  const out = join(outDir, "models.py");
  const args = [
    "uvx", "--quiet", "--python", "3.11", "--from", DATAMODEL_CODEGEN, "datamodel-codegen",
    "--input", bundledPath, "--input-file-type", "jsonschema", "--output", out,
    "--output-model-type", "pydantic_v2.BaseModel", "--target-python-version", "3.11",
    "--use-standard-collections", "--use-union-operator", "--use-subclass-enum", "--use-default", "--strict-nullable", "--capitalise-enum-members",
    "--extra-fields", "forbid", "--disable-timestamp", "--use-double-quotes", "--collapse-root-models",
    "--custom-file-header", "# GENERATED by packages/dia-types/scripts/gen.ts from schema/*.schema.json. DO NOT EDIT.",
  ];
  const r = Bun.spawnSync(args, { stdout: "inherit", stderr: "inherit" });
  if (r.exitCode !== 0) throw new Error("datamodel-codegen failed");
  return readFileSync(out, "utf8").replace(/\r\n/g, "\n");
}

const schema = bundle();
const bundledText = JSON.stringify(schema, null, 2) + "\n";
const tmpBundle = join(mkdtempSync(join(tmpdir(), "dia-bundle-")), "dia.schema.json");
writeFileSync(tmpBundle, bundledText);

const outputs: Record<string, string> = {
  "dist/dia.schema.json": bundledText,
  "ts/generated.ts": await typescript(schema),
  "py/dia_types/models.py": python(tmpBundle),
};

let stale = false;
for (const [rel, text] of Object.entries(outputs)) {
  const path = join(ROOT, rel);
  if (CHECK) {
    let current = "";
    try { current = readFileSync(path, "utf8").replace(/\r\n/g, "\n"); } catch {}
    if (current !== text) { console.error(`stale: packages/dia-types/${rel}`); stale = true; }
  } else {
    writeFileSync(path, text);
    console.log(`wrote packages/dia-types/${rel}`);
  }
}
if (stale) { console.error("Run `bun run gen:types` and commit the result."); process.exit(1); }
if (CHECK) console.log("generated types are up to date");
